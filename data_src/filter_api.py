def filter_api_calls_for_sample(
    args: argparse.Namespace
) -> List[APICall]:
    """
    Filter all candidate API calls in a sample and return the retained subset. [file:1][web:82]
    x_text: original text
    calls: candidate API calls
    tau_f: threshold, values of 0.5, 1.0, and 2.0 are listed in the paper's table
    """
    df = pd.read_csv(args.file_path, sep='\t')
    df['is_leaf'] = False
    for i, row in df.iterrows():
        x_text = row['x_text']
        api_name = row['api_name']
        api_input = row['api_input']
        result = row['api_result']
        df.loc[i, 'is_leaf'] = filter_single_api_call(
            x_text, 
            APICall(api_name, api_input, -1, result), 
            args.tau_f
        )

    leaf_df = df[df['is_leaf'] == True].reset_index(drop=True)
    leaf_df = insert_api_with_offset(leaf_df)

    if args.output_path:
        leaf_df.to_csv(args.output_path, sep='\t', index=False)

    print(f"Filter result: {leaf_df.shape[0]/df.shape[0]}({leaf_df.shape[0]}/{df.shape[0]})")


